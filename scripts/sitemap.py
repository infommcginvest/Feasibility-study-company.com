#!/usr/bin/env python3
"""sitemap.xml for feasibility-study-company.com, generated from the pages.

Every served page whose robots meta says index is listed, with lastmod set to
the page's own date: its JSON-LD dateModified, or for a page that has none, the
"updated" param of its byline line region. A page with neither stops the run.
Pages marked noindex (/404.html, /tools/nda/) are left out.

    python3 scripts/sitemap.py           rewrite sitemap.xml
    python3 scripts/sitemap.py --check   exit 1 if sitemap.xml is out of date

Run it after any change to a page's date (scripts/byline.py renders the visible
line from the same date), and after a lane adds or removes pages.
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import links  # noqa: E402

ROOT = links.ROOT
OUT = os.path.join(ROOT, "sitemap.xml")
ORDER = ["", "practice-areas", "asset-classes", "states", "case-studies", "research-notes",
         "analytical-framework", "the-practice", "tools", "accessibility", "privacy", "terms"]


def page_date(s):
    m = re.search(r'"dateModified"\s*:\s*"(\d{4}-\d{2}-\d{2})"', s)
    if m:
        return m.group(1)
    m = re.search(r'<!--fsc:line-(?:state|asset) (\{.*?\})-->', s)
    if m:
        return json.loads(m.group(1))["updated"]
    return None


def indexable(s):
    m = re.search(r'<meta name="robots" content="([^"]*)"', s)
    robots = (m.group(1) if m else "index, follow").lower()
    return "noindex" not in robots


def entries(site):
    out, missing = [], []
    for rel, url in site.pages:
        s = site.text(rel)
        if not indexable(s):
            continue
        d = page_date(s)
        if d is None:
            missing.append(url)
            continue
        out.append((url, d))
    if missing:
        raise SystemExit(f"indexable pages with no date: {missing}")

    def key(e):
        first = e[0].strip("/").split("/")[0]
        rank = ORDER.index(first) if first in ORDER else len(ORDER)
        return (rank, e[0].count("/") > 2, e[0])
    return sorted(out, key=key)


def render(es):
    lines = ['<?xml version="1.0" encoding="UTF-8"?>',
             "<!-- Generated by scripts/sitemap.py from the pages: every indexable page, lastmod = the page's own date. Do not edit by hand. -->",
             '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    for url, d in es:
        lines.append("  <url>")
        lines.append(f"    <loc>{links.SITE}{url}</loc>")
        lines.append(f"    <lastmod>{d}</lastmod>")
        lines.append("  </url>")
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


def main(argv):
    site = links.Site()
    new = render(entries(site))
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    if "--check" in argv:
        print("sitemap.xml " + ("up to date" if new == old else "out of date"))
        return 0 if new == old else 1
    if new != old:
        with open(OUT, "w", encoding="utf-8") as fh:
            fh.write(new)
    print(f"sitemap.xml: {new.count('<url>')} URLs")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
