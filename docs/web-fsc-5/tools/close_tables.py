#!/usr/bin/env python3
"""Write docs/web-fsc-5/CLOSE-TABLES.md from the register, so the numbers in
CLOSE come from the files and are not typed.

    python3 docs/web-fsc-5/tools/close_tables.py
"""
import csv
import json
import os
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(HERE)))
DATA = os.path.join(ROOT, 'data', 'markets')
OUT = os.path.join(ROOT, 'docs', 'web-fsc-5', 'CLOSE-TABLES.md')


def jl(name):
    return json.load(open(os.path.join(DATA, name), encoding='utf-8'))


def main():
    L = ['# WEB-FSC-5 close tables', '', 'Generated by docs/web-fsc-5/tools/close_tables.py from data/markets/. Do not edit by hand.', '']
    src = jl('sources.json')
    L += ['## Sources and series by status', '', '| fetch source | status | vintage | period | series files | reason |', '|---|---|---|---|---|---|']
    for r in src['sources']:
        L.append(f'| {r["id"]} | {r["status"]} | {r.get("vintage") or ""} | {r.get("period") or ""} | {len(r.get("series") or [])} | {(r.get("reason") or "").replace("|", "/")} |')
    rows = {}
    for f in sorted(os.listdir(os.path.join(DATA, 'series'))):
        s = json.load(open(os.path.join(DATA, 'series', f)))
        rows[f[:-5]] = (len(s['values']), len(s.get('nulls', {})))
    L += ['', '| series file | geographies with values | geographies null by design |', '|---|---|---|']
    for k, (a, b) in rows.items():
        L.append(f'| {k} | {a} | {b} |')

    geo = jl('geographies.json')
    ms = geo['markets']
    L += ['', '## Market compositions', '', f'{len(ms)} markets; by kind: ' + ', '.join(f'{k} {v}' for k, v in sorted(Counter(m["kind"] for m in ms).items()))
          + '; by composition source: ' + ', '.join(f'{k} {v}' for k, v in sorted(Counter(m["composition_source"] for m in ms).items()))
          + f'; review rows {sum(m["review"] for m in ms)}.', '',
          '### Review rows for the owner', '', '| market | kind | composition source | counties (resolved) or places | basis | reason |', '|---|---|---|---|---|---|']
    for m in ms:
        if m['review']:
            comp = m['components']
            cname = {r['fips']: r['name'] for r in geo['counties']['rows']}
            res = m.get('resolved') or {}   # the counties the register uses, not the composer's list
            names = [cname.get(f, f) for f in res.get('counties') or []] or [p['name'] for p in comp['places']]
            if m.get('ct'):
                ct = m['foia']['ct']
                names = [f'legacy: {", ".join(ct["legacy"])}; planning regions: {", ".join(ct["pr"])}']
            L.append(f'| {m["state"]}/{m["slug"]} | {m["kind"]} | {m["composition_source"]} | {", ".join(names)[:300]} | {(m.get("basis") or "").replace("|", "/")} | {(m.get("reason") or "").replace("|", "/")[:300]} |')

    nm = jl('naics-map.json')
    ev = jl('naics-evidence.json')
    L += ['', '## NAICS map', '', '| class | fit | NAICS 2022 | FOIA loans, all statuses, any edition | by edition set |', '|---|---|---|---|---|']
    for r in nm['classes']:
        e = ev['classes'][r['slug']]
        L.append(f'| {r["slug"]} | {r["fit"]} | {", ".join(r["naics2022"]) if len(r["naics2022"]) <= 8 else str(len(r["naics2022"])) + " codes"} | {e["foia_loans_total"]:,} | {"; ".join(f"{k}: {v:,}" for k, v in e["foia_loans_by_edition_set"].items())} |')
    L.append('\nRows with a blank NaicsCode (in "all", in no class): ' + '; '.join(f'{p} {v["rows_all_statuses"]:,} rows, {v["loans_net_of_cancellations"]:,} net of cancellations' for p, v in ev['blank_naics'].items())
             + f'. Class figures are complete from FY{ev["class_figures_complete_from_fy"]}: before that, the blanks fall on whole industries. Distinct NAICS codes on loans that sit in no class: {ev["distinct_codes_in_no_class"]:,}.')

    sm = jl('foia-status-map.json')
    sc = jl('foia-status-counts.json')
    L += ['', '## FOIA status table', '', '| program | status | category | rows | with FirstDisbursementDate | with ChargeOffDate | GrossChargeOffAmount > 0 |', '|---|---|---|---|---|---|---|']
    for prog, files in sc['counts'].items():
        evd = files.get('_evidence', {})
        tot = Counter()
        for f, d in files.items():
            if f != '_evidence':
                tot.update(d)
        for st, n in sorted(tot.items()):
            L.append(f'| {prog} | `{st}` | {sm["programs"][prog][st]["category"]} | {n:,} | {evd.get(st + "|first_disbursement_date", 0):,} | {evd.get(st + "|charge_off_date", 0):,} | {evd.get(st + "|charge_off_amount_gt0", 0):,} |')

    g = jl('foia-geocoding.json')
    tot = {}
    for r in g['by_state']:
        t = tot.setdefault(r['program'], [0, 0, 0])
        t[0] += r['rows']; t[1] += r['unmatched_blank_county']; t[2] += r['in_a_site_market_composition']
    L += ['', '## FOIA geocoding', '', '| program | rows | ProjectCounty present (method project_county) | unmatched (blank ProjectCounty) | match rate | in a site market composition |', '|---|---|---|---|---|---|']
    for p, t in tot.items():
        L.append(f'| {p} | {t[0]:,} | {t[0] - t[1]:,} | {t[1]:,} | {100 * (t[0] - t[1]) / t[0]:.3f}% | {t[2]:,} |')
    L.append('\nThe ZIP to ZCTA method is not available (the relationship file is on www2.census.gov). By-state rates are in data/markets/foia-geocoding.json; the lowest with at least 100 rows: '
             + '; '.join(f'{r["program"]} {r["state"]} {100 * r["match_rate_project_county"]:.2f}% of {r["rows"]:,}' for r in sorted((r for r in g['by_state'] if r['rows'] >= 100), key=lambda r: r['match_rate_project_county'])[:5]) + '.')

    rec = jl('reconciliation.json')
    L += ['', '## Reconciliation', '', f'FOIA us totals by program and approval FY against the raw files: {sum(r["match"] for r in rec["us_by_program_fy"])} of {len(rec["us_by_program_fy"])} cells match (rows, loans net of cancellations, volume).', '']
    for p, v in rec['states_vs_us'].items():
        L.append(f'- {p}: sum of states {v["sum_of_states_loans"]:,} vs us {v["us_loans"]:,}; difference {v["difference"]} = loans with a blank ProjectState ({v["loans_with_blank_project_state"]}).')

    au = list(csv.DictReader(open(os.path.join(DATA, 'audit.csv'), encoding='utf-8')))
    mk = [r for r in au if r['level'] == 'market']
    L += ['', '## Audit', '', f'{len(mk)} markets; standalone {sum(r["standalone"] == "yes" for r in mk)}; not standalone {sum(r["standalone"] != "yes" for r in mk)}.', '',
          '### Texas', '', '| geography | specific values | suppressed | component values | standalone | reason |', '|---|---|---|---|---|---|']
    for r in au:
        if r['geo'] == 'tx' or r['geo'].startswith('texas/'):
            L.append(f'| {r["geo"]} | {r["specific_values"]} | {r["suppressed_values"]} | {r["component_values"]} | {r["standalone"]} | {r["reason"]} |')
    L += ['', '### Not standalone, by reason', '']
    for k, v in Counter(r['reason'].split(':')[0] for r in mk if r['standalone'] != 'yes').items():
        L.append(f'- {k}: {v}')
    open(OUT, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('wrote', os.path.relpath(OUT, ROOT))


if __name__ == '__main__':
    main()
